    /** @brief Convert a native TIFF image to PNG without decoding unbounded dimensions.
     * @param data Native image bytes.
     * @return PNG data, or nil for unsupported/oversized images.
     */
    NSData *png_from_tiff(NSData *data) {
      if (!data || data.length > 32 * 1024 * 1024) {
        return nil;
      }
      CGImageSourceRef source = CGImageSourceCreateWithData((CFDataRef) data, nullptr);
      if (!source) {
        return nil;
      }
      NSDictionary *properties = [(NSDictionary *) CGImageSourceCopyPropertiesAtIndex(source, 0, nullptr) autorelease];
      const auto width = [properties[(NSString *) kCGImagePropertyPixelWidth] unsignedLongLongValue];
      const auto height = [properties[(NSString *) kCGImagePropertyPixelHeight] unsignedLongLongValue];
      if (!width || !height || width > 16384 || height > 16384 || width * height > 64000000) {
        CFRelease(source);
        return nil;
      }
      CGImageRef image = CGImageSourceCreateImageAtIndex(source, 0, nullptr);
      CFRelease(source);
      if (!image) {
        return nil;
      }
      NSBitmapImageRep *bitmap = [[[NSBitmapImageRep alloc] initWithCGImage:image] autorelease];
      CGImageRelease(image);
      return [bitmap representationUsingType:NSBitmapImageFileTypePNG properties:@ {}];
    }

    /** @brief Return the native pasteboard type for a negotiated MIME type.
     * @param mime Supported MIME type.
     * @return Native type or nil.
     */
    NSString *native_type(const std::string &mime) {
      if (mime == "text/plain") {
        return NSPasteboardTypeString;
      }
      if (mime == "text/html") {
        return NSPasteboardTypeHTML;
      }
      if (mime == "text/rtf") {
        return NSPasteboardTypeRTF;
      }
      if (mime == "image/png") {
        return NSPasteboardTypePNG;
      }
      return nil;
    }

    /** @brief Read one consistent native clipboard snapshot on the Cocoa thread.
     * @param board Pasteboard to inspect.
     * @return Encoded supported types, or null when content must not be shared.
     */
    nlohmann::json read_uncached(NSPasteboard *board) {
      const auto revision = board.changeCount;
      for (NSString *marker in @[@"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType", @"org.nspasteboard.AutoGeneratedType", NSPasteboardTypeFileURL]) {
        if ([board.types containsObject:marker]) {
          return nullptr;
        }
      }
      auto items = nlohmann::json::object();
      std::size_t size = 0;
      for (const auto *mime : {"text/plain", "text/html", "text/rtf", "image/png"}) {
        NSData *data = [board dataForType:native_type(mime)];
        if (!data && std::string_view(mime) == "image/png") {
          data = png_from_tiff([board dataForType:NSPasteboardTypeTIFF]);
        }
        if (!data) {
          continue;
        }
        size += data.length;
        if (size > max_bytes) {
          return nullptr;
        }
        items[mime] = [[data base64EncodedStringWithOptions:0] UTF8String];
      }
      // Unknown types (including Finder file URLs) are not an instruction to clear the peer.
      if (board.changeCount != revision || (items.empty() && board.types.count)) {
        return nullptr;
      }
      return items;
    }

    /** @brief Reuse an unchanged native snapshot instead of re-encoding images every poll.
     * @return Current bounded snapshot, or null for concealed/unsupported contents.
     */
    nlohmann::json read_native() {
      static std::string name;
      static NSInteger revision = -1;
      static nlohmann::json cached;
      NSPasteboard *board = pasteboard();
      const std::string current_name = board.name.UTF8String;
      const auto current_revision = board.changeCount;
      if (name != current_name || revision != current_revision) {
        cached = read_uncached(board);
        name = current_name;
        revision = current_revision;
      }
      return cached;
    }
  }  // namespace

  nlohmann::json read() {
    __block nlohmann::json result;
    void (^operation)(void) = ^{ @autoreleasepool { result = read_native(); } };
    if ([NSThread isMainThread]) {
      operation();
    } else {
      dispatch_sync(dispatch_get_main_queue(), operation);
    }
    return result;
  }

  bool write(const nlohmann::json &items, const std::string &expected) {
    if (!valid_items(items)) {
      return false;
    }
    __block bool success = false;
    void (^operation)(void) = ^{
      @autoreleasepool {
        const auto current = read_native();
        if (current.is_null() || digest(current) != expected) {
          return;
        }
        NSPasteboardItem *item = [[[NSPasteboardItem alloc] init] autorelease];
        for (const auto &[mime, value] : items.items()) {
          NSString *encoded = [NSString stringWithUTF8String:value.get_ref<const std::string &>().c_str()];
          NSData *data = [[[NSData alloc] initWithBase64EncodedString:encoded options:0] autorelease];
          if (!data) {
            return;
          }
          if (mime == "text/plain" && ![[[NSString alloc] initWithData:data encoding:NSUTF8StringEncoding] autorelease]) {
            return;
          }
          if (mime == "image/png") {
            const auto *bytes = static_cast<const unsigned char *>(data.bytes);
            constexpr unsigned char signature[] = {137, 80, 78, 71, 13, 10, 26, 10};
            if (data.length < 24 || !std::equal(std::begin(signature), std::end(signature), bytes)) {
              return;
            }
            const auto dimension = [bytes](int offset) {
              return (uint32_t(bytes[offset]) << 24) | (uint32_t(bytes[offset + 1]) << 16) | (uint32_t(bytes[offset + 2]) << 8) | bytes[offset + 3];
            };
            const auto width = dimension(16), height = dimension(20);
            if (!width || !height || width > 16384 || height > 16384 || uint64_t(width) * height > 64000000 || ![[[NSBitmapImageRep alloc] initWithData:data] autorelease]) {
              return;
            }
          }
          if (![item setData:data forType:native_type(mime)]) {
            return;
          }
        }
        NSPasteboard *board = pasteboard();
        [board clearContents];
        success = items.empty() || [board writeObjects:@[item]];
      }
    };
    if ([NSThread isMainThread]) {
      operation();
    } else {
      dispatch_sync(dispatch_get_main_queue(), operation);
    }
    return success;
  }

#ifdef SUNSHINE_TESTS
  namespace testing {
    void begin() {
      test_board = [[NSPasteboard pasteboardWithUniqueName] retain];
    }

    void end() {
      [test_board releaseGlobally];
      [test_board release];
      test_board = nil;
    }

    void conceal() {
      [test_board declareTypes:@[NSPasteboardTypeString, @"org.nspasteboard.ConcealedType"] owner:nil];
      [test_board setString:@"concealed fixture" forType:NSPasteboardTypeString];
      [test_board setString:@"1" forType:@"org.nspasteboard.ConcealedType"];
    }

    void tiff() {
      NSBitmapImageRep *image = [[[NSBitmapImageRep alloc] initWithBitmapDataPlanes:nullptr pixelsWide:2 pixelsHigh:2 bitsPerSample:8 samplesPerPixel:4 hasAlpha:YES isPlanar:NO colorSpaceName:NSDeviceRGBColorSpace bytesPerRow:0 bitsPerPixel:0] autorelease];
      std::memset(image.bitmapData, 0, image.bytesPerRow * image.pixelsHigh);
      [test_board declareTypes:@[NSPasteboardTypeTIFF] owner:nil];
      [test_board setData:image.TIFFRepresentation forType:NSPasteboardTypeTIFF];
    }
  }  // namespace testing
#endif
